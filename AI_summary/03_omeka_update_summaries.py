"""
This script updates Omeka S database items with the bilingual summaries generated by
step 02. It reads the French summaries from Summaries_FR_TXT and the English ones from
Summaries_EN_TXT, and updates the corresponding Omeka S items by writing both to
bibo:shortDescription as two ``@language``-tagged literals — ``fr`` and ``en`` — in a
single PATCH per item.

bibo:shortDescription is the AI-summary field for articles and documents in IWAC —
it is what the Hugging Face export surfaces as ``descriptionAI``. Do NOT write these
summaries to dcterms:abstract: that property carries publisher/author abstracts on
issues and scholarly references, and the HF ``documents`` subset exports it as a
separate ``abstract`` column.

The French target sets ``adopt_untagged``: the ~12,300 summaries written before this
pipeline became bilingual carry no ``@language`` at all, so the French write claims
and tags the existing literal rather than appending a second French value beside it.

Each summary is annotated with the AI model that produced it, as an
``iwac:summaryModel`` value annotation on the bibo:shortDescription value — the same
provenance convention AI_ocr_extraction/03 uses for ``iwac:ocrModel``. Both languages
carry the annotation, since one model produced both. The model is chosen
interactively, or with --model.

The write step itself lives in ``common/omeka_text_updater.py``, shared with the
OCR, OCR-correction and transcription updaters.

Requirements:
- Environment variables: OMEKA_BASE_URL, OMEKA_KEY_IDENTITY, OMEKA_KEY_CREDENTIAL
- Summary files in Summaries_FR_TXT and Summaries_EN_TXT (from 02_AI_generate_summaries.py)
- Omeka S API access with appropriate permissions

Usage:
    python 03_omeka_update_summaries.py                        # prompts for model
    python 03_omeka_update_summaries.py --model gpt-5.6-luna
    python 03_omeka_update_summaries.py --model gemini-flash --dry-run
"""

import argparse
import logging
import sys
from pathlib import Path

from rich.console import Console

# Configure logging to track script execution and errors
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')

# Shared Omeka client and IWAC instance configuration
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from common.omeka_client import OmekaClient
from common.omeka_text_updater import (
    PropertyTarget,
    run_text_updates,
    texts_from_directory,
    updates_from_directory,
)
from common.iwac_config import (
    AI_MODEL_ITEMS,
    IWAC_SUMMARY_MODEL_PROPERTY_ID,
    model_annotation_value,
    select_model_key,
)
from common.log_redaction import install_credential_redaction

# Credentials ride in Omeka query strings and provider headers; keep them
# out of anything urllib3 or an SDK decides to log.
install_credential_redaction()

# The Omeka property that carries the AI summary for articles and documents.
# Exported to Hugging Face as ``descriptionAI``.
SUMMARY_TERM = 'bibo:shortDescription'
SUMMARY_MODEL_TERM = 'iwac:summaryModel'

#: Must match ``02_AI_generate_summaries.py``.
FRENCH_DIR = "Summaries_FR_TXT"
ENGLISH_DIR = "Summaries_EN_TXT"

#: Step 02's default; offered as step 03's default answer so the two agree
#: unless the operator ran 02 with --model.
DEFAULT_MODEL_KEY = "gpt-5.6-luna"

console = Console()


def main() -> int:
    """Upload the generated summaries, annotated with the model that wrote them."""
    parser = argparse.ArgumentParser(
        description="Upload bilingual (fr/en) summaries to Omeka S with "
                    "iwac:summaryModel provenance."
    )
    parser.add_argument(
        "--model", choices=list(AI_MODEL_ITEMS),
        help="AI model that produced the summaries. Prompts interactively when omitted.",
    )
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Fetch each item and report what would change, but write nothing.",
    )
    parser.add_argument(
        "--yes", action="store_true",
        help="Skip the interactive confirmation before writing.",
    )
    parser.add_argument(
        "--backup-dir", type=Path, default=None,
        help="Where each item's pre-write JSON is dumped before its PATCH "
             "(default: <pipeline>/backups). The only route back from a bulk overwrite.",
    )
    parser.add_argument(
        "--no-backup", action="store_true",
        help="Do not dump pre-write payloads. Not recommended.",
    )
    args = parser.parse_args()

    try:
        client = OmekaClient.from_env()
    except ValueError as e:
        logging.error(str(e))
        return 1

    # Resolve the property ID at runtime: IDs vary between Omeka S installs,
    # and writing with the wrong one stores the summary under another property.
    description_property_id = client.get_property_id(SUMMARY_TERM)
    if description_property_id is None:
        logging.error(f"Could not resolve property ID for {SUMMARY_TERM} — aborting.")
        return 1
    logging.info(f"Resolved {SUMMARY_TERM} to property ID {description_property_id}")

    # Which model wrote these summaries? Recorded as an iwac:summaryModel annotation.
    model_key = args.model or select_model_key(default=DEFAULT_MODEL_KEY)
    if model_key is None:
        return 1
    model = AI_MODEL_ITEMS[model_key]
    annotation = model_annotation_value(
        client.base_url, model_key, IWAC_SUMMARY_MODEL_PROPERTY_ID, "AI Model - Summary"
    )
    # One model produced both renderings, so both literals carry the annotation.
    # Only the French target adopts an untagged legacy literal — an English write
    # must never claim a value that predates this pipeline.
    french_target = PropertyTarget(
        term=SUMMARY_TERM,
        property_id=description_property_id,
        property_label='shortDescription',
        annotation_term=SUMMARY_MODEL_TERM,
        annotation_value=annotation,
        language="fr",
        adopt_untagged=True,
    )
    english_target = PropertyTarget(
        term=SUMMARY_TERM,
        property_id=description_property_id,
        property_label='shortDescription',
        annotation_term=SUMMARY_MODEL_TERM,
        annotation_value=annotation,
        language="en",
    )
    logging.info(
        f"Annotating with {SUMMARY_MODEL_TERM} -> {model['display_title']} (item {model['item_id']})"
    )

    pipeline_dir = Path(__file__).resolve().parent
    french_folder = pipeline_dir / FRENCH_DIR
    english_folder = pipeline_dir / ENGLISH_DIR
    absent = [str(folder) for folder in (french_folder, english_folder) if not folder.exists()]
    if absent:
        logging.error(f"Summary folder(s) not found: {', '.join(absent)}")
        logging.error("Please run 02_AI_generate_summaries.py first to generate summary files.")
        return 1

    updates = updates_from_directory(french_folder)
    english_texts = texts_from_directory(english_folder)
    if not updates:
        logging.warning(f"No .txt files found in {french_folder}")
        return 0

    # Pair the two folders. A French summary with no English counterpart is still
    # written — a partially completed step 02 should not block the whole batch —
    # but it is reported, because writing one language silently would look like a
    # complete update.
    french_only = 0
    for update in updates:
        english = english_texts.pop(update.item_id, "")
        if english:
            update.extra_values.append((english_target, english))
        else:
            french_only += 1
    if french_only:
        logging.warning(f"{french_only} item(s) have no English summary — French only")
    if english_texts:
        logging.warning(
            f"{len(english_texts)} English summary file(s) have no French counterpart "
            f"and will be skipped: {sorted(english_texts)[:5]}"
        )
    logging.info(f"Found {len(updates)} summary files to process")

    # Folder names only: the absolute paths wrap and break the panel's alignment.
    confirm_lines = [
        f"Source folder:    {pipeline_dir}",
        f"                  {FRENCH_DIR}/ + {ENGLISH_DIR}/",
    ]
    if french_only:
        confirm_lines.append(f"French only:      {french_only} of {len(updates)}")

    backup_dir = None if args.no_backup else (args.backup_dir or pipeline_dir / "backups")

    stats = run_text_updates(
        client, updates, french_target,
        console=console,
        dry_run=args.dry_run,
        require_confirmation=not args.yes,
        extra_confirm_lines=confirm_lines,
        description="Updating summaries...",
        backup_dir=backup_dir,
        backup_label="summaries",
    )
    if not stats:
        return 1  # operator declined

    return 0 if stats["failed"] == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
